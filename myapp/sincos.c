/* ============================================================================
 * 一次取出 sin/cos
 * cos(a) = sin(a + 90度)，而 90 度正好是表的 1/4 圈 = 256 个索引，
 * 所以 cos 不需要第二张表，索引偏移 256 即可（1024 点表时 SIN_TAB_SIZE/4）
 * ==========================================================================*/
void Foc_SinCos_U16(uint16_t angle, float *ps, float *pc)
{
    uint16_t idx  = angle >> SIN_TAB_FRAC_BITS;
    uint16_t frac = angle &  SIN_TAB_FRAC_MASK;
    uint16_t i_s  = idx;
    uint16_t i_c  = (idx + (SIN_TAB_SIZE / 4)) & SIN_TAB_MASK;
    float    k    = (float)frac * (1.0f / 64.0f);

    *ps = sin_tab[i_s] + (sin_tab[(i_s + 1) & SIN_TAB_MASK] - sin_tab[i_s]) * k;
    *pc = sin_tab[i_c] + (sin_tab[(i_c + 1) & SIN_TAB_MASK] - sin_tab[i_c]) * k;
}